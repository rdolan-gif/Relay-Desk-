import sanitizeHtml from 'sanitize-html';

/**
 * Sanitises email HTML (spec 11.2 step 1): keeps formatting, tables and inline images,
 * strips scripts, event handlers, forms, iframes and remote-content tricks. Rendered in
 * a sandboxed frame in the UI as a second layer.
 */
export function sanitizeEmailHtml(html: string): string {
  return sanitizeHtml(html, {
    allowedTags: [
      'p',
      'br',
      'div',
      'span',
      'b',
      'strong',
      'i',
      'em',
      'u',
      's',
      'strike',
      'sub',
      'sup',
      'small',
      'big',
      'font',
      'center',
      'h1',
      'h2',
      'h3',
      'h4',
      'h5',
      'h6',
      'blockquote',
      'pre',
      'code',
      'hr',
      'ul',
      'ol',
      'li',
      'dl',
      'dt',
      'dd',
      'a',
      'img',
      'table',
      'thead',
      'tbody',
      'tfoot',
      'tr',
      'th',
      'td',
      'caption',
      'colgroup',
      'col',
    ],
    allowedAttributes: {
      '*': ['style', 'align', 'valign', 'width', 'height', 'dir', 'class'],
      a: ['href', 'name', 'target', 'rel', 'title'],
      img: ['src', 'alt', 'title', 'width', 'height'],
      font: ['color', 'face', 'size'],
      td: ['colspan', 'rowspan', 'bgcolor'],
      th: ['colspan', 'rowspan', 'bgcolor'],
      table: ['cellpadding', 'cellspacing', 'border', 'bgcolor'],
    },
    allowedSchemes: ['http', 'https', 'mailto', 'cid', 'data'],
    allowedSchemesByTag: { img: ['http', 'https', 'cid', 'data'] },
    allowedStyles: {
      '*': {
        color: [/.*/],
        'background-color': [/.*/],
        'text-align': [/.*/],
        'font-size': [/.*/],
        'font-weight': [/.*/],
        'font-style': [/.*/],
        'font-family': [/.*/],
        'text-decoration': [/.*/],
        margin: [/.*/],
        padding: [/.*/],
        border: [/.*/],
        width: [/.*/],
        'line-height': [/.*/],
      },
    },
    transformTags: { a: sanitizeHtml.simpleTransform('a', { rel: 'noopener noreferrer', target: '_blank' }) },
  });
}
