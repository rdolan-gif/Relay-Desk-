import { Inject, Injectable } from '@nestjs/common';
import { createHash, randomUUID } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { CONFIG, type AppConfig } from '../config/config';

/**
 * File storage for raw emails and attachments. Files live on the server's disk under
 * STORAGE_DIR (cheapest option, owner O-9); an S3-compatible driver can replace this
 * later without changing callers.
 */
@Injectable()
export class StorageService {
  constructor(@Inject(CONFIG) private readonly config: AppConfig) {}

  async put(prefix: string, data: Buffer, ext = 'bin'): Promise<{ key: string; size: number; checksum: string }> {
    const now = new Date();
    const key = path.posix.join(
      prefix,
      String(now.getUTCFullYear()),
      String(now.getUTCMonth() + 1).padStart(2, '0'),
      `${randomUUID()}.${ext}`,
    );
    const full = this.resolve(key);
    await mkdir(path.dirname(full), { recursive: true });
    await writeFile(full, data);
    return { key, size: data.length, checksum: createHash('sha256').update(data).digest('hex') };
  }

  get(key: string): Promise<Buffer> {
    return readFile(this.resolve(key));
  }

  /** Keys are generated by `put`; refuse anything that would escape the storage folder. */
  private resolve(key: string): string {
    const root = path.resolve(this.config.STORAGE_DIR);
    const full = path.resolve(root, key);
    if (!full.startsWith(root + path.sep)) throw new Error('Invalid storage key');
    return full;
  }
}
